# DBTITLE 1,Nested extract -> {prefix}_extracted_nested (input + extracted, GT joined below)
import json

nested_schema_sql = json.dumps(PAYSTUB_SCHEMA).replace("'", "''")
flat_schema_sql = json.dumps(FLAT_SCHEMA).replace("'", "''")
instr_sql = INSTRUCTIONS.replace("'", "''")

# Nested + flat extraction in one pass over the bronze table.
spark.sql(f"""
CREATE OR REPLACE TABLE {tables['extracted_nested']}_staging AS
SELECT
  path,
  to_json(parsed) AS input,
  ai_extract(
    parsed, '{nested_schema_sql}',
    options => map('version', '{extract_version}', 'enableConfidenceScores', 'true',
                   'instructions', '{instr_sql}')
  ) AS extracted,
  ai_extract(
    parsed, '{flat_schema_sql}',
    options => map('version', '{extract_version}', 'enableConfidenceScores', 'true',
                   'instructions', '{instr_sql}')
  ) AS extracted_flat_variant
FROM {tables['bronze']}
""")
print(f"staged extraction -> {tables['extracted_nested']}_staging")

# COMMAND ----------

# MAGIC %md
# MAGIC ## 3. Flatten the flat-schema extraction → `{prefix}_extracted_flat`
# MAGIC
# MAGIC One value column `<field>` and one confidence column `<field>_extract_conf` per
# MAGIC flat field — the exact contract Recipe 03 reads.

# COMMAND ----------

select_clauses = ["path"]
for col_name, variant_path, sql_type in FIELD_SPECS:
    select_clauses.append(
        f"variant_get(extracted_flat_variant, '$.response.{variant_path}.value', '{sql_type}') AS {col_name}"
    )
    select_clauses.append(
        f"variant_get(extracted_flat_variant, '$.response.{variant_path}.confidence_score', 'double') AS {col_name}_extract_conf"
    )

spark.sql(f"""
CREATE OR REPLACE TABLE {tables['extracted_flat']} AS
SELECT {', '.join(select_clauses)}
FROM {tables['extracted_nested']}_staging
""")
display(spark.table(tables["extracted_flat"]))

