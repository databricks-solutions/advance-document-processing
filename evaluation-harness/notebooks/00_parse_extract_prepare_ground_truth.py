# MAGIC %md
# MAGIC # Recipe 00 — Parse + Extract + Prepare Ground-Truth Tables
# MAGIC
# MAGIC The **data-prep front-end** for the evaluation harness. It runs the AI Functions
# MAGIC once and builds the ground-truth tables that Recipes **03** (flat) and **04**
# MAGIC (nested) consume, so those two recipes stay self-contained and measure-only.
# MAGIC
# MAGIC Pipeline:
# MAGIC
# MAGIC 1. **`ai_parse_document`** on the sample paystub PDFs → one parsed VARIANT per doc.
# MAGIC 2. **`ai_extract` twice** on that parsed output:
# MAGIC    - a **nested** schema (`PAYSTUB_SCHEMA`, objects + arrays) → feeds Recipe 04.
# MAGIC    - a **flat** schema (scalars + `gross`/`net_pay`, projected to the 13 columns of
# MAGIC      `paystub_ground_truth.csv`) → feeds Recipe 03.
# MAGIC 3. **Join** the parse/extract output with the two curated answer files that ship in
# MAGIC    `../sample_data/` to write **four tables**:
# MAGIC
# MAGIC | Table | Columns | Consumer |
# MAGIC |---|---|---|
# MAGIC | `{prefix}_bronze_parsed` | `path`, `parsed` | shared / Recipe 01 |
# MAGIC | `{prefix}_extracted_flat` | `path`, `<field>`, `<field>_extract_conf` | Recipe 03 (predictions) |
# MAGIC | `{prefix}_ground_truth_simple` | `doc_id`, `<field>` … | Recipe 03 (labels) |
# MAGIC | `{prefix}_extracted_nested` | `path`, `input`, `extracted`, `ground_truth` | Recipe 04 (self-contained) |
# MAGIC
# MAGIC The nested table is built by joining the extraction output with the labels in
# MAGIC `sample_data/paystub_ground_truth_ai_extract.jsonl`, so no pre-built nested CSV is
# MAGIC needed.
# MAGIC
# MAGIC > **Sample-data caveat:** the curated ground truth covers only scalar fields plus
# MAGIC > the `gross` / `net_pay` objects. The nested schema's `array` fields
# MAGIC > (`income_item`, `deduction_item`) and address objects are extracted but have **no
# MAGIC > labels**, so Recipe 04's array paths are not exercised until richer ground truth
# MAGIC > exists.
# MAGIC
# MAGIC Requires **DBR 18.2+ / serverless v3+** for `ai_extract` 2.1.
# MAGIC
# MAGIC > **Sample PDFs.** This recipe reads the paystub PDFs from the UC volume set by
# MAGIC > the widgets below — the documents themselves live in
# MAGIC > `../../ai-extract-word-level-citation/sample_data/` (`paystub_synth_[1-4].pdf`,
# MAGIC > generated by `scripts/generate_sample_paystubs.py`). Upload them to your volume
# MAGIC > first with `scripts/upload_pdfs.sh` (see `../README.md`).

