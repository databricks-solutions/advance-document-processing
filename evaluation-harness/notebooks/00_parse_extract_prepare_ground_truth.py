from pyspark.sql import functions as F
from pyspark.sql.functions import col, expr

dbutils.fs.mkdirs(image_path)

raw = (
    spark.read.format("binaryFile")
    .option("recursiveFileLookup", "false")
    .option("pathGlobFilter", "*.pdf")
    .load(source_path)
    .filter(~col("path").contains("/images/"))
)

parsed = (
    raw.withColumn(
        "parsed",
        expr(
            "ai_parse_document(content, "
            "map('version', '2.0', "
            f"'imageOutputPath', '{image_path}', "
            "'descriptionElementTypes', '*'))"
        ),
    )
    .select("path", "parsed")
)

(
    parsed.write.format("delta")
    .mode("overwrite")
    .option("overwriteSchema", "true")
    .saveAsTable(tables["bronze"])
)

display(spark.sql(f"""
SELECT
  path,
  parsed:metadata:file_metadata:file_name::string AS file_name,
  size(variant_get(parsed, '$.document.elements', 'array<variant>')) AS element_count
FROM {tables['bronze']}
ORDER BY file_name
"""))

