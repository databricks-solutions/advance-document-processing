# MAGIC ## 4. Load curated answers & build ground-truth tables
# MAGIC
# MAGIC Both answer files ship in `../sample_data/` and are read with pandas (robust to
# MAGIC the multi-line JSON in the nested file). We normalize the doc id to a join key —
# MAGIC basename → strip extension → lowercase → drop non-alphanumerics — the same key
# MAGIC Recipes 03/04 use, so `.../paystub_synth_1.pdf` matches `paystub_synth_1`.

# COMMAND ----------

import re

import pandas as pd


def norm_key(s):
    base = re.sub(r"^.*/", "", str(s))
    base = re.sub(r"\.[^.]+$", "", base)
    return re.sub(r"[^A-Za-z0-9]", "", base).lower()


norm_key_udf = F.udf(norm_key)

# --- simple ground truth (flat CSV) -> {prefix}_ground_truth_simple ---
simple_pdf = pd.read_csv(simple_gt_csv, dtype=str).dropna(how="all")
gt_simple = spark.createDataFrame(simple_pdf).withColumn("join_key", norm_key_udf(F.col("doc_id")))
gt_simple.write.format("delta").mode("overwrite").option("overwriteSchema", "true").saveAsTable(
    tables["gt_simple"]
)
print(f"{tables['gt_simple']}: {gt_simple.count()} rows")
display(spark.table(tables["gt_simple"]))

# COMMAND ----------

# --- nested ground truth (JSONL) joined with parse+extract -> {prefix}_extracted_nested ---
nested_pdf = pd.read_json(nested_gt_jsonl, lines=True)
# ground_truth is a dict per row; store as a JSON string column for a stable schema.
nested_pdf["ground_truth"] = nested_pdf["ground_truth"].map(json.dumps)
gt_nested = (
    spark.createDataFrame(nested_pdf[["doc_id", "ground_truth"]])
    .withColumn("join_key", norm_key_udf(F.col("doc_id")))
)

staging = spark.table(f"{tables['extracted_nested']}_staging").withColumn(
    "join_key", norm_key_udf(F.col("path"))
)

extracted_nested = (
    staging.join(gt_nested, "join_key", "inner")
    .select("path", "input", "extracted", "ground_truth")
)
extracted_nested.write.format("delta").mode("overwrite").option("overwriteSchema", "true").saveAsTable(
    tables["extracted_nested"]
)

matched = extracted_nested.count()
print(f"{tables['extracted_nested']}: {matched} rows (input + extracted + ground_truth)")
assert matched == gt_nested.count(), (
    f"join dropped rows: {matched} joined vs {gt_nested.count()} labels — check doc ids."
)
display(spark.sql(f"SELECT path, to_json(extracted) AS extracted_json, ground_truth FROM {tables['extracted_nested']}"))

