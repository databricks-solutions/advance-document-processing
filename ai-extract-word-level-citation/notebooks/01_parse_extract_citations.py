# DBTITLE 1,Cell 20
RESPONSE_ROOT = "response"

select_clauses = [
    "path",
    "image_uri",
    "parsed_elements",
    # image_name = page-image basename if present, else the pdf basename
    "COALESCE(element_at(split(image_uri, '/'), -1), "
    "element_at(split(path, '/'), -1)) AS image_name",
]

# Scalar fields — use FIELD_SPECS to map flat column names to nested VARIANT paths
for col_name, variant_path, sql_type in FIELD_SPECS:
    select_clauses.append(
        f"variant_get(paystub_extracted, '$.{RESPONSE_ROOT}.{variant_path}.value', '{sql_type}') AS {col_name}"
    )
    select_clauses.append(
        f"variant_get(paystub_extracted, '$.{RESPONSE_ROOT}.{variant_path}.confidence_score', 'double') AS {col_name}_extract_conf"
    )
    select_clauses.append(
        f"variant_get(paystub_extracted, '$.{RESPONSE_ROOT}.{variant_path}.citation_ids', 'array<int>') AS {col_name}_citation_ids"
    )

# Array fields — stored directly at $.response.<array_field> (no .value wrapper).
# Per-element sub-field citations live inside each element, not at the array level.
for af in ARRAY_FIELDS:
    select_clauses.append(f"variant_get(paystub_extracted, '$.{RESPONSE_ROOT}.{af}', 'variant') AS {af}")

# Keep the two citation VARIANTs whole for NB02.
select_clauses.append("variant_get(paystub_extracted, '$.metadata.citations', 'variant') AS citations")
select_clauses.append("variant_get(paystub_extracted, '$.metadata.pages', 'variant') AS citation_pages")

flat_sql = f"""
CREATE OR REPLACE TABLE {pipeline_config['flat_table']} AS
SELECT
  {','.join(select_clauses)}
FROM {pipeline_config['extracted_table']}
"""
spark.sql(flat_sql)
display(spark.table(pipeline_config["flat_table"]))

