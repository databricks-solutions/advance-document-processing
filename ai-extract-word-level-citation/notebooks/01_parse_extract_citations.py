# Databricks notebook source
# MAGIC %md
# MAGIC # 01 — Parse + Extract with Citations (Paystubs)
# MAGIC
# MAGIC POC notebook 1 of 2 for **second-level bounding boxes** on `ai_extract`
# MAGIC entities (see `../README.md` and `second-level-bbox-recommendation.md`).
# MAGIC
# MAGIC The workflow is:
# MAGIC
# MAGIC 1. `ai_parse_document` → collect elements + saved page images (bronze).
# MAGIC 2. `ai_extract` v2.1 with **`enableCitations`** on the whole parsed
# MAGIC    document → entity value + per-field confidence + **element-level
# MAGIC    citation bboxes**.
# MAGIC 3. Flatten to the shape the visualization in NB02 expects
# MAGIC    (`image_name`, `<field>`, `<field>_extract_conf`, `<field>_citation_ids`,
# MAGIC    `citations`, `citation_pages`).
# MAGIC
# MAGIC > **Why the parsed VARIANT, not plain text, into `ai_extract`:** citation
# MAGIC > bboxes only exist because the input carries layout geometry. Plain text
# MAGIC > has no coordinates, so feeding the parsed VARIANT is what makes
# MAGIC > `citations[].bbox[].coord` populated.
# MAGIC
# MAGIC Requires **DBR 18.2+ / serverless env v3+** for `ai_extract` 2.1.

